const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');

(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--disable-webgl']});
  try {
    const page=await browser.newPage({viewport:{width:1100,height:850}});
    const base=pathToFileURL(path.resolve(__dirname,'../experiments/typed-world/index.html')).href;
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'?scene=blank');
    assert.equal(await page.locator('#pattern option').count(),409);
    assert.equal(await page.locator('#rule option').count(),9);
    assert.equal(await page.locator('#resolver option').count(),4);
    await page.selectOption('#pattern','bays/osc2');
    await page.selectOption('#rule','callahan');
    await page.selectOption('#resolver','guard');
    await page.selectOption('#angle','2');
    await page.click('#save');
    await page.reload();
    await page.selectOption('#hand','0');
    assert.deepEqual(await page.evaluate(()=>['pattern','rule','resolver','angle'].map(k=>document.getElementById(k).value)),
      ['bays/osc2','callahan','guard','2']);
    await page.locator('#board').click();
    assert.match(await page.locator('#notice').textContent(),/Jade plantou/);
    await page.selectOption('#scene','cross');await page.click('#reset');
    assert.equal(await page.locator('#precedence').inputValue(),'1');
    assert.equal(await page.locator('#colorby').inputValue(),'rule');
    assert.deepEqual(await page.locator('#legend span').allTextContents(),['Bays','Callahan']);
    await page.selectOption('#colorby','owner');assert(await page.locator('#legend').isHidden());
    await page.click('#step');assert.match(await page.locator('#gen').textContent(),/^G10 · disparo \+1$/);
    for(const scene of ['cross','ally']){
      await page.goto(base+'?scene='+scene);
      await page.evaluate(()=>{for(let i=0;i<3;i++)document.querySelector('#many').click();});
      const counts=await page.locator('#coverage').textContent();
      assert.equal(counts,scene==='cross'?'Linhagens · Bays em travessia 18 · Callahan em contato 0':'Linhagens · Bays em travessia 2 · Callahan em contato 41');
    }
    await page.goto(base+'?scene=engulf&bank=1000000');
    assert.equal(await page.locator('#owner option').count(),3);
    await page.evaluate(()=>{for(let i=0;i<16;i++)document.querySelector('#many').click();});
    assert.match(await page.locator('#coverage').textContent(),/2\.562 \/ 2\.562 locais/);
    assert.match(await page.locator('#coverage').textContent(),/Cobalto · G177/);
    assert.match(await page.locator('#damage').textContent(),/Baixas amigas 62 \/ 0 \/ 0/);
    await page.goto(base+'?scene=recovery');
    await page.evaluate(()=>{for(let i=0;i<12;i++)document.querySelector('#many').click();});
    assert.match(await page.locator('#accounts').textContent(),/3.028,5/);
    assert.match(await page.locator('#damage').textContent(),/Células liquidadas 3 \/ 0/);
    await page.goto(base+'?scene=orbit');
    await page.evaluate(()=>{for(let i=0;i<6;i++)document.querySelector('#many').click();});
    assert.match(await page.locator('#damage').textContent(),/Baixas inimigas diretas 108 \/ 0/);
    await page.goto(base+'?scene=arena&bots=tactical&seed=8221&f=16');
    await page.evaluate(()=>{for(let i=0;i<12;i++)document.querySelector('#many').click();});
    assert.equal(await page.locator('#verdict').textContent(),'Jade · G2851');
    assert.match(await page.locator('#brain').textContent(),/Testes locais 72 · Compras Jade \/ Cobre 6 \/ 6/);
    assert.match(await page.locator('#damage').textContent(),/Baixas inimigas diretas 8 \/ 0/);
    await page.goto(base+'?scene=all&seed=33&arb=ballot&g=14&site=1781');
    assert.equal(await page.locator('#owner option').count(),3);
    assert.equal(await page.locator('#arb option').count(),10);
    assert.match(await page.locator('#contest-detail').textContent(),/G14 · sítio 1781.*ciclo no topo/);
    const proof=await page.locator('#election-audit').textContent();
    for(const edge of ['A vence B','B vence C','C vence A'])assert(proof.includes(edge+' · 2 a 1'));
    await page.selectOption('#ballot','robustness');await page.click('#save');await page.reload();
    await page.selectOption('#hand','1');assert.equal(await page.locator('#ballot').inputValue(),'robustness');
    await page.goto(base+'?scene=all&arb=matrix&by=rule&edges=111100001111000111100111101111111111&g=2&site=225');
    assert.equal(await page.locator('#matrix-editor td button').count(),72);
    assert.match(await page.locator('#matrix-editor').textContent(),/Sem dominante/);
    assert.match(await page.locator('#contest-detail').textContent(),/ciclo no topo/);
    await page.getByRole('button',{name:'Ordem da lista',exact:true}).click();
    assert.match(await page.locator('#matrix-editor').textContent(),/Dominante: callahan/);
    await page.click('#reset');assert.equal(await page.locator('#legend span').count(),9);
    await page.click('#next-triple');assert.match(await page.locator('#contest-detail').textContent(),/sítio/);
    await page.goto(base+'?scene=physical&g=11&site=246');
    assert.equal(await page.locator('#arb').inputValue(),'ecology');
    assert.equal(await page.locator('#legend span').count(),9);
    assert.match(await page.locator('#contest-detail').textContent(),/G11 · sítio 246.*Andreen.*ciclo no topo/);
    assert.equal((await page.locator('#election-audit').textContent()).split('2 a 1').length-1,3);
    await page.goto(base+'?scene=coexist');
    assert.equal(await page.locator('#owner option').count(),1);
    await page.evaluate(()=>{for(let i=0;i<32;i++)document.querySelector('#many').click();});
    assert.equal(await page.locator('#legend span').count(),9);
    assert.match(await page.locator('#accounts').textContent(),/4.410,8/);
    await page.goto(base+'?scene=arena&bots=both');
    await page.click('#many');assert.match(await page.locator('#gen').textContent(),/G32/);
    await page.setViewportSize({width:360,height:780});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors,[]);
    console.log('PASS: typed stamps, saved composition, paid placement, contested precedence, orbital interface and native full-planet shock.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
