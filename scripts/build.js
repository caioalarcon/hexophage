// Assemble the portable distribution. Feature modules and markup live under src/.
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const bundle = async (entry, define = {}) => {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    charset: 'utf8',
    target: 'es2020',
    write: false,
    define,
  });
  return result.outputFiles[0].text;
};

// A Blob worker also works when the user opens a downloaded file without a server.
const worker = await bundle('src/world/planet.worker.js');
const game = await bundle('src/start.js', { HEXOPHAGE_PLANET_WORKER: JSON.stringify(worker) });
let html = await readFile('src/shell.html', 'utf8');
for (const [marker, path] of html.matchAll(/<!-- include ([\w./-]+) -->/g)) {
  const partial = await readFile('src/' + path, 'utf8');
  html = html.replace(marker, () => partial.trimEnd());
}
html = html.replace(
  '<html',
  '<!-- Generated by npm run build. Edit src/shell.html and the feature modules. -->\n<html',
);
html = html.replace('<!-- game -->', () => game.replace(/<\/script/gi, '<\\/script'));
await writeFile('index.html', html);
