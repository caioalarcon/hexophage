// Compact exact age histogram over the last 128 frames of each isolated seed.
import {writeFileSync} from 'node:fs';
import {ruleProfiles, resolveRuleProfile} from '../../src/match/rule-profiles.js';
import {seedPatternAges, advancePattern} from '../../src/patterns/planar-simulation.js';

const horizon=1024, window=128, samples={};
for (const id of Object.keys(ruleProfiles).filter(id=>id!=='custom')) {
  const {physics,gameplay}=resolveRuleProfile(id);
  const result=samples[id]={};
  for (const p of gameplay.atlas??gameplay.patterns) {
    let ages=seedPatternAges(p), totalBirths=0;
    const initial=ages.size, counts=new Uint32Array(horizon+2);
    for (let g=1; g<=horizon; g++) {
      const step=advancePattern(ages,256,physics);
      ages=step.next;
      if (g>horizon-window) {
        totalBirths+=step.births;
        for (const age of ages.values()) counts[age]++;
      }
    }
    const bands=[];
    for(let age=1;age<counts.length;){
      const start=age, count=counts[age++];
      while(age<counts.length && counts[age]===count) age++;
      if(count) bands.push(start,age-1,count);
    }
    result[p.id]=[initial,totalBirths/window,bands];
  }
}
writeFileSync(new URL('../../src/patterns/physical-yields.js', import.meta.url),
  '// Generated by experiments/economic-starts/measure-ages.mjs.\n'+
  '// [initial cells, mean births, [first age, last age, occurrences per age, ...]] in G897–1024.\n'+
  'export const physicalYields = '+JSON.stringify(samples)+';\n');
