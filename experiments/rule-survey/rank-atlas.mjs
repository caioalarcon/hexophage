// These three generated tables contain only IDs, booleans and numeric fields.
import {readFileSync, writeFileSync} from 'node:fs';
import {ruleProfiles} from '../../src/match/rule-profiles.js';
import {stampCatalog} from '../../src/bots/brain/proposals.js';

function rows(file) {
  const [head,...lines]=readFileSync(new URL(file,import.meta.url),'utf8').trimEnd().split(/\r?\n/);
  const columns=head.split(',');
  return lines.map(line=>{
    const values=line.split(',');
    if (values.length!==columns.length) throw Error('Invalid row in '+file);
    return Object.fromEntries(columns.map((key,i)=>[key,values[i]]));
  });
}
const cohorts=['cold-1','warm-2','warm-3','cold-control'];
const matches=rows('matches.csv');
const offered=new Set();
const scores={};
const purchaseCounts=new Map(), outside=new Set();
for (const row of rows('stamp-trials.csv')) {
  if (row.F!=='32' || !cohorts.includes(row.cohort)) continue;
  const key=row.rule+'/'+row.stamp;
  purchaseCounts.set(key,(purchaseCounts.get(key)??0)+Number(row.purchases));
}
for (const row of rows('auditions.csv')) {
  const key=row.rule+'/'+row.stamp;
  offered.add(key);
  if (row.thinkable==='false') outside.add(key);
}

// Production learners key duplicate legacy RLEs by first lexicographic ID.
// The atlas displays the canonical title of the same shape (e.g. osc42 → p42).
const keysByRule={};
for (const [id,profile] of Object.entries(ruleProfiles)) {
  if (profile.compile) continue;
  for (const cohort of cohorts) {
    if (matches.filter(m=>m.rule===id && m.F==='32' && m.cohort===cohort).length!==1)
      throw Error('Missing or repeated match '+id+'/'+cohort);
  }
  const {gameplay}=profile, byRle=new Map();
  const rleById=new Map(gameplay.patterns.map(p=>[p.id,p.rle]));
  for (const stamp of stampCatalog(gameplay.patterns)) byRle.set(rleById.get(stamp.id),stamp.id);
  keysByRule[id]=new Map((gameplay.atlas??gameplay.patterns).map(p=>[p.id,id+'/'+byRle.get(p.rle)]));
}
for (const row of rows('isolated.csv')) {
  const key=keysByRule[row.rule].get(row.id);
  if (!offered.has(key)) throw Error('Missing audition '+key);
  (scores[row.rule]??={})[row.id]=[
    row.complete==='true'?Number(row.lateFlow):null,
    outside.has(key)?null:purchaseCounts.get(key)??0,
  ];
}
writeFileSync(new URL('../../src/patterns/survey-scores.js',import.meta.url),
  '// Generated by experiments/rule-survey/rank-atlas.mjs. [isolated flow, open-deck purchases]\nexport const surveyScores = '+JSON.stringify(scores)+';\n');
